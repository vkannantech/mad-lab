// Auto-detects the Android SDK on any machine and writes/repairs local.properties.
// Fixes "SDK location not found" and stale sdk.dir paths copied from another PC.
// Applied from settings.gradle.kts, so it runs on first sync (Android Studio) or first ./gradlew call.

import java.io.File
import java.util.Properties

val propsFile = File(settingsDir, "local.properties")
val props = Properties().apply { if (propsFile.exists()) propsFile.inputStream().use { load(it) } }

fun isSdk(path: String?): Boolean =
    !path.isNullOrBlank() && File(path).let { File(it, "platforms").isDirectory || File(it, "platform-tools").isDirectory }

val current = props.getProperty("sdk.dir")
if (!isSdk(current)) {
    val home = System.getProperty("user.home")
    val candidates = listOfNotNull(
        System.getenv("ANDROID_HOME"),
        System.getenv("ANDROID_SDK_ROOT"),
        System.getenv("LOCALAPPDATA")?.let { "$it\\Android\\Sdk" },   // Windows default
        "$home/AppData/Local/Android/Sdk",                             // Windows fallback
        "$home/Library/Android/sdk",                                   // macOS default
        "$home/Android/Sdk",                                           // Linux default
        "$home/Android/sdk",
        "$home/Apps/sdk-android",
        "/opt/android-sdk",
        "/usr/lib/android-sdk",
        "C:\\Android\\Sdk",
    )
    val found = candidates.firstOrNull { isSdk(it) }
    if (found != null) {
        props.setProperty("sdk.dir", File(found).absolutePath.replace("\\", "/"))
        propsFile.outputStream().use { props.store(it, "Auto-generated by gradle/sdk-autodetect.gradle.kts - machine specific, do not commit") }
        println("[sdk-autodetect] sdk.dir = ${props.getProperty("sdk.dir")}" + if (current != null) " (replaced invalid: $current)" else "")
    } else {
        println("[sdk-autodetect] WARNING: Android SDK not found. Install Android Studio, or set ANDROID_HOME, or add sdk.dir to local.properties.")
    }
}
