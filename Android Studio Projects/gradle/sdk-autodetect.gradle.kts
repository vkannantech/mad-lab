// Auto-detects the Android SDK on any machine and writes/repairs local.properties.
// Fixes "SDK location not found" and stale sdk.dir paths copied from another PC.
// Applied from settings.gradle.kts, so it runs on first sync (Android Studio) or first ./gradlew call.
//
// Search order (first valid SDK wins):
//   1. sdk.dir already in local.properties (kept if it still exists)
//   2. ANDROID_HOME / ANDROID_SDK_ROOT environment variables
//   3. The SDK path Android Studio itself saved (newest Android Studio version first)
//   4. Windows registry (Android SDK installer)
//   5. Default install folders on Windows / macOS / Linux

import java.io.File
import java.util.Properties

val propsFile = File(settingsDir, "local.properties")
val props = Properties().apply { if (propsFile.exists()) propsFile.inputStream().use { load(it) } }

fun isSdk(path: String?): Boolean =
    !path.isNullOrBlank() && File(path).let { File(it, "platforms").isDirectory || File(it, "platform-tools").isDirectory }

val home: String = System.getProperty("user.home")
val isWindows = System.getProperty("os.name").lowercase().contains("win")

// Android Studio stores its SDK location in <config>/options/android.sdk.path.xml
fun androidStudioSdkPaths(): List<String> {
    val configRoots = listOfNotNull(
        System.getenv("APPDATA")?.let { "$it/Google" },                       // Windows
        "$home/Library/Application Support/Google",                           // macOS
        (System.getenv("XDG_CONFIG_HOME") ?: "$home/.config") + "/Google",    // Linux
    )
    return configRoots
        .flatMap { root -> File(root).listFiles { f -> f.isDirectory && f.name.startsWith("AndroidStudio") }?.toList() ?: emptyList() }
        .sortedByDescending { it.name }                                       // newest Android Studio first
        .mapNotNull { dir ->
            val xml = File(dir, "options/android.sdk.path.xml")
            if (!xml.isFile) return@mapNotNull null
            Regex("""androidSdkAbsolutePath"\s+value="([^"]+)"""").find(xml.readText())?.groupValues?.get(1)
                ?.replace("\$USER_HOME\$", home)
        }
}

fun windowsRegistrySdkPaths(): List<String> {
    if (!isWindows) return emptyList()
    return listOf("HKLM\\SOFTWARE\\Android SDK Tools", "HKCU\\SOFTWARE\\Android SDK Tools", "HKLM\\SOFTWARE\\WOW6432Node\\Android SDK Tools")
        .mapNotNull { key ->
            runCatching {
                val p = ProcessBuilder("reg", "query", key, "/v", "Path").redirectErrorStream(true).start()
                val out = p.inputStream.bufferedReader().readText(); p.waitFor()
                Regex("""Path\s+REG_SZ\s+(.+)""").find(out)?.groupValues?.get(1)?.trim()
            }.getOrNull()
        }
}

val current = props.getProperty("sdk.dir")
if (!isSdk(current)) {
    val localAppData = System.getenv("LOCALAPPDATA")
    val candidates: List<String> = listOfNotNull(
        System.getenv("ANDROID_HOME"),
        System.getenv("ANDROID_SDK_ROOT"),
    ) + androidStudioSdkPaths() + windowsRegistrySdkPaths() + listOfNotNull(
        localAppData?.let { "$it/Android/Sdk" },                 // Windows default
        "$home/AppData/Local/Android/Sdk",
        "C:/Android/Sdk", "D:/Android/Sdk", "C:/Android/android-sdk",
        System.getenv("ProgramFiles(x86)")?.let { "$it/Android/android-sdk" },
        "$home/Library/Android/sdk",                             // macOS default
        "/opt/homebrew/share/android-commandlinetools",          // Homebrew (Apple Silicon)
        "/usr/local/share/android-commandlinetools",             // Homebrew (Intel)
        "/usr/local/share/android-sdk",
        "$home/Android/Sdk", "$home/Android/sdk",                // Linux default
        "$home/android-sdk", "/opt/android-sdk", "/usr/lib/android-sdk", "/opt/android/sdk",
    )
    val found = candidates.firstOrNull { isSdk(it) }
    if (found != null) {
        props.setProperty("sdk.dir", File(found).absolutePath.replace("\\", "/"))
        propsFile.outputStream().use { props.store(it, "Auto-generated by gradle/sdk-autodetect.gradle.kts - machine specific, do not commit") }
        println("[sdk-autodetect] sdk.dir = ${props.getProperty("sdk.dir")}" + if (current != null) " (replaced invalid: $current)" else "")
    } else {
        println("[sdk-autodetect] WARNING: Android SDK not found. Open Android Studio once (it installs the SDK), or set ANDROID_HOME, or add sdk.dir to local.properties.")
    }
}
